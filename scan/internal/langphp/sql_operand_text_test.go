package langphp

import (
	"strings"
	"testing"
)

// TestPHPQuotedOperands reads SQL text, with @ for an operand that must be quoted
// and ~ for an integer.
func TestPHPQuotedOperands(t *testing.T) {
	for sql, want := range map[string]bool{
		"SELECT a FROM t WHERE b = '@'":                                              true,
		"  select * from `db`.`t` where b='@' and c >= 5;  ":                         true,
		"SELECT a FROM t WHERE (b LIKE '%@%' OR c <> '@') AND NOT (d IN ('x', '@'))": true,
		"SELECT a FROM t WHERE ((b = '@')) ORDER BY c LIMIT 1, 2;;":                  true,
		"SELECT a FROM t JOIN u ON (t.id = u.id) WHERE b = '@' GROUP BY c":           true,
		"INSERT INTO t ( a, b ) VALUES ( '@', 'it''s' ), ('@', 1);":                  true,
		"INSERT INTO `d`.t (a) VALUES ('@')":                                         true,
		"REPLACE INTO t (a) VALUES ('@')":                                            true,
		"INSERT INTO t SET a = '@', b = '@'":                                         true,
		"UPDATE t SET a = '@' WHERE b != '@' LIMIT 1":                                true,
		"DELETE FROM t WHERE b < '@' OR b > 'x' OR b <= '@'":                         true,
		"SELECT a FROM t WHERE b = 'a''@'":                                           true,
		"SELECT a FROM t WHERE b IN ('x', 'y') AND c IN (1)\tAND d = '\r\n@'":        true,
		"SELECT z, Z, a_b, a0, a9 FROM t\r\nWHERE b > '@' OR c >= 'a @' ORDER BY a":  true,
		"SELECT a FROM t WHERE b >= '@' ORDER BY a":                                  true,
		"SELECT a FROM t WHERE b = 1 AND (c = '@') OR (d = '@')":                     true,
		"SELECT a FROM t WHERE c = '@' OR d =":                                       true,
		"SELECT a FROM t WHERE b = 1 OR (c = '@')":                                   true,
		"SELECT a FROM t WHERE b = `@`":                                              false,
		"SELECT a FROM t WHERE b = '\x7f@'":                                          false,
		"SELECT a FROM t WHERE b IN (_gbk'@')":                                       false,
		"SELECT INTO t WHERE b = '@'":                                                false,
		"SELECT a x . run (b) FROM t WHERE c = '@'":                                  false,
		"INSERT INTO t x run (a) VALUES ('@')":                                       false,
		"INSERT INTO d . t SELECT run (a) FROM u WHERE b = '@'":                      false,
		"INSERT INTO t SELECT run (a) FROM u WHERE b = '@'":                          false,
		"SELECT a FROM t WHERE b = ~ AND c IN (~, 1) AND d = '~' LIMIT ~ OFFSET ~":   true,
		"SELECT a FROM t LIMIT~":                                                     false,
		"SELECT a FROM t WHERE x = ~AND y = 1":                                       false,
		"SELECT a FROM t LIMIT '~'":                                                  false,
		"SELECT a FROM t LIMIT '@'":                                                  false,
		"~ SELECT a FROM t":                                                          false,
		"SELECT a FROM t WHERE x = 5-~":                                              false,
		"SELECT a FROM t WHERE x = ~e5":                                              false,
		"SELECT a FROM t WHERE x = ~~":                                               false,
		"SELECT a FROM t WHERE x = '~~'":                                             false,
		"":                                                                           false,
		";":                                                                          false,
		"SELECT a FROM t WHERE b = @":                                                false,
		"SELECT a FROM t WHERE b = 'x' AND c = @":                                    false,
		"SELECT a FROM t WHERE b = '@@'":                                             false,
		"SELECT a FROM t WHERE b = '@":                                               false,
		"SELECT a FROM t WHERE b = ''@''":                                            false,
		"SELECT a FROM t ORDER BY `@`":                                               false,
		"SELECT `a FROM t WHERE b = '@'":                                             false,
		"SELECT a FROM t WHERE b = \"@\"":                                            false,
		"SELECT a FROM t WHERE b = 'x\\' AND c = '@'":                                false,
		"SELECT a FROM t WHERE b = '\xbf@'":                                          false,
		"SELECT a FROM t WHERE b = '\x00@'":                                          false,
		"SELECT é FROM t WHERE b = '@'":                                              false,
		"SELECT a FROM t -- it's\n WHERE b = '@'":                                    false,
		"SELECT a FROM t # it's\n WHERE b = '@'":                                     false,
		"SELECT a FROM t /* it's */ WHERE b = '@'":                                   false,
		"SELECT a FROM t WHERE b = '@'; DELETE FROM t":                               false,
		"SELECT a FROM t; SELECT a FROM t WHERE b = '@'":                             false,
		"PREPARE p FROM 'SELECT a FROM t WHERE id = @'":                              false,
		"CALL run('@')":                                                              false,
		"SET names = '@'":                                                            false,
		"EXECUTE IMMEDIATE '@'":                                                      false,
		"SELECT run('@')":                                                            false,
		"SELECT a FROM t WHERE b = run('@')":                                         false,
		"SELECT a FROM t WHERE b = run ('@')":                                        false,
		"SELECT a FROM t WHERE b = `run`('@')":                                       false,
		"SELECT a FROM t WHERE value ('@') = 1":                                      false,
		"SELECT run(b) FROM t WHERE b = '@'":                                         false,
		"SELECT run(q) FROM t, (SELECT '@' AS q) u":                                  false,
		"SELECT a FROM t WHERE b = '@' UNION SELECT 1":                               false,
		"SELECT a FROM t WHERE MATCH (b) AGAINST ('@')":                              false,
		"SELECT a FROM t WHERE b REGEXP '@'":                                         false,
		"SELECT a FROM t WHERE b LIKE 'x' ESCAPE '@'":                                false,
		"SELECT a FROM t WHERE b LIKE '@' ESCAPE '|'":                                false,
		"SELECT a FROM t WHERE b = _gbk'@'":                                          false,
		"SELECT a FROM t WHERE b = x'@'":                                             false,
		"SELECT a FROM t WHERE b = 'x' '@'":                                          false,
		"SELECT a FROM t WHERE b = '@' 'x'":                                          false,
		"SELECT a FROM t WHERE b = '@' COLLATE c":                                    false,
		"SELECT '@' FROM t":                                                          false,
		"SELECT a, '@' FROM t":                                                       false,
		"SELECT a FROM t WHERE ('@')":                                                false,
		"SELECT a FROM t WHERE (1, '@') = b":                                         false,
		"SELECT a FROM t WHERE b => '@'":                                             false,
		"SELECT a FROM t WHERE b = '@' INTO OUTFILE 'f'":                             false,
		"SELECT a FROM t WHERE c = '@' AND b = 'x' INTO OUTFILE 'f'":                 false,
		"SELECT a INTO OUTFILE '@' FROM t":                                           false,
		"INSERT INTO t SELECT a INTO OUTFILE 'f' FROM u WHERE b = '@'":               false,
		"INSERT INTO run('@')":                                                       false,
		"INSERT INTO t (a) VALUES (run('@'))":                                        false,
		"INSERT t (a) VALUES ('@')":                                                  false,
		"SELECT a FROM (SELECT a FROM t WHERE b = '@') u":                            false,
		"SELECT a FROM x.run (b) WHERE c = '@'":                                      false,
		"SELECT x FROM t (a) WHERE b = '@'":                                          false,
		"SELECT a FROM t WHERE (b = '@'":                                             false,
		"SELECT a FROM t WHERE b = '@')":                                             false,
		"SELECT a FROM t WHERE b IN (1), run (2) OR c = '@'":                         false,
		"SELECT a, (b) FROM t WHERE c = '@'":                                         false,
		"SELECT a FROM t WHERE b = 5 - '@'":                                          false,
		"SELECT a FROM t WHERE b = :n AND c = '@'":                                   false,
		"SELECT a FROM t WHERE [b] = '@'":                                            false,
		"INSERT INTO x . run (a) VALUES ('@')":                                       true,
		"INSERT INTO x run . t (a) VALUES ('@')":                                     false,
		"UPDATE x SET into = 1 WHERE b = '@'":                                        false,
		"INSERT LOW_PRIORITY x (a) VALUES ('@')":                                     false,
	} {
		if got := phpQuotedOperands(strings.NewReplacer("@", string(rune(phpOperandMark)), "~", string(rune(phpNumberMark))).Replace(sql)); got != want {
			t.Errorf("%q: %v, want %v", sql, got, want)
		}
	}
}
